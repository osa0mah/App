export function findDestination(
  input: string,
): "القرآن" | "تعلّم" | "الفتاوى" | "التسميع" | null {
  if (/فتوى|فتاوى|باز|فوزان|عثيمين/.test(input)) return "الفتاوى";
  if (/تفسير|نزول|مقاصد|تعلم|تعلّم/.test(input)) return "تعلّم";
  if (/تسميع|حفظ|سمع/.test(input)) return "التسميع";
  if (/سورة|سوره|قرآن|قران|الفاتحة|الإخلاص/.test(input)) return "القرآن";
  return null;
}
